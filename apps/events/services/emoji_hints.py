FALLBACK = ["⭐", "✅", "📌", "💡", "🌟"]  # 合う言葉がなかったとき
LIMIT = 5


def suggest(name: str) -> list[str]:
    """名前に合いそうな絵文字（多くても5つ、重なりなし）。合う言葉がなければ、よく使うもの。"""
    found: list[str] = []
    for words, emojis in HINTS:
        if any(w in name for w in words):
            found += [e for e in emojis if e not in found]
    return found[:LIMIT] if found else list(FALLBACK)


def hints_for_client() -> dict:
    """端末（app.js）に渡す辞書。サーバーと同じ候補を、名前を打つたびに出し直すため。"""
