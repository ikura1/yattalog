FALLBACK = ["⭐", "✅", "📌", "💡", "🌟"]  # 合う言葉がなかったとき
LIMIT = 5

_KATAKANA = {code: code - 0x60 for code in range(0x30A1, 0x30F7)}  # ァ〜ヶ → ぁ〜ゖ


def normalize(text: str) -> str:
    """比べる前にそろえる：全角・半角（NFKC）、大小の文字、カタカナ → ひらがな。emoji.js の normalizeHint() と同じ"""
    return unicodedata.normalize("NFKC", text).lower().translate(_KATAKANA)


def suggest(name: str) -> list[str]:
    """名前に合いそうな絵文字（多くても5つ、重なりなし）。合う言葉がなければ、よく使うもの。

    当たった言葉が長い組ほど先に並べる（「自転車」は「車」より先）。同じ長さなら、名前の先に出てくる言葉の組、
    それも同じなら辞書の上にある組を先にする。emoji.js の suggestEmojis() も同じ当て方にしている。
    """
    text = normalize(name)
    ranked = []
    for order, (words, emojis) in enumerate(HINTS):
        best = None
        for w in map(normalize, words):
            at = text.find(w)
            if at >= 0 and (best is None or (-len(w), at) < best):
                best = (-len(w), at)
        if best:
            ranked.append((best, order, emojis))
    found: list[str] = []
    for _, _, emojis in sorted(ranked):
        found += [e for e in emojis if e not in found]
    return found[:LIMIT] if found else list(FALLBACK)


def hints_for_client() -> dict:
    """端末（emoji.js）に渡す辞書。サーバーと同じ候補を、名前を打つたびに出し直すため。"""
    return {
        "hints": [[list(words), list(emojis)] for words, emojis in HINTS],
        "fallback": list(FALLBACK),
        "limit": LIMIT,
    }
